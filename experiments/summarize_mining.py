"""Turn the JSON outputs of ``fas mine`` into a readable Markdown summary.

Usage: python experiments/summarize_mining.py results/mining results/mining/summary.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def _arcs(graph: dict) -> str:
    return ", ".join(f"{a[0]}->{a[1]}" + (f"x{a[2]}" if len(a) > 2 else "") for a in graph["arcs"])


def vertex_section(data: dict, name: str) -> list[str]:
    rows = data["rows"]
    unexplained = [r for r in rows if r["unexplained_always_forced"]]
    out = [f"## Vertex forcing: `{name}`", "",
           f"{data['graphs']} isomorphism classes ({data['kind']}, n in {data['n_values']}), "
           f"{sum(r['occurrences'] for r in rows)} vertex occurrences with in- and out-arcs, "
           f"{len(rows)} signatures (w_in, w_out, L_two_cycle, nu_cycles).", "",
           f"Signatures where 'delete v, pay one side' is always optimal but NOT explained by "
           f"w_side <= L(v): **{len(unexplained)}**.", ""]
    for r in unexplained:
        out.append(f"- {r['signature']}: {r['occurrences']} occurrences")
    partial = sorted((r for r in rows if 0 < max(r["forced_in_fraction"], r["forced_out_fraction"]) < 1),
                     key=lambda r: -r["occurrences"])[:8]
    if partial:
        out += ["", "Largest signatures where forcing holds only sometimes (local data does not decide it):", "",
                "| signature | occurrences | forced in | forced out |", "|---|---|---|---|"]
        out += [f"| {r['signature']} | {r['occurrences']} | {r['forced_in_fraction']} | {r['forced_out_fraction']} |"
                for r in partial]
    fal = data.get("falsification")
    if fal:
        hyps = fal["hypotheses"]
        refuted = [h for h in hyps if h["refuted"]]
        out += ["", f"Falsification on {fal['graphs']} random graphs: {len(hyps)} 'always forced' hypotheses, "
                f"{len(refuted)} refuted, {sum(1 for h in hyps if not h['refuted'] and h['confirmed'])} confirmed "
                f"and never refuted, {sum(1 for h in hyps if not h['refuted'] and not h['confirmed'])} untested.",
                f"Unexplained survivors: {sum(1 for h in hyps if not h['refuted'] and not h['explained_by_two_cycle_bound'])}."]
    return out + [""]


def arc_section(data: dict, name: str) -> list[str]:
    rows = data["rows"]
    uniform = [r for r in rows if r["uniform"]]
    out = [f"## Arc status: `{name}`", "",
           f"{data['graphs']} classes, {sum(r['occurrences'] for r in rows)} arcs on cycles, {len(rows)} signatures "
           f"(antiparallel, tail out/in, head out/in weights); {len(uniform)} signatures have a single label.", ""]
    fal = data.get("falsification")
    if fal:
        hyps = fal["hypotheses"]
        refuted = [h for h in hyps if h["refuted"]]
        survivors = [h for h in hyps if not h["refuted"] and h["confirmed"]]
        out += [f"Hypotheses 'arc with this signature is in all / no optimal FAS' (uniform, >= 10 occurrences): "
                f"{len(hyps)}; refuted on {fal['graphs']} random larger graphs: {len(refuted)}; "
                f"survived with >= 1 confirmation: {len(survivors)}.", "",
                "Survival is weak evidence: `tests/test_tools.py::test_mined_hypothesis_refuted_by_hand_example` "
                "refutes a surviving 'none' signature with a hand-built 7-vertex graph.", "",
                "Smallest refutations (first 10):", ""]
        for h in sorted(refuted, key=lambda h: len(h["first_refutation"]["graph"]["arcs"]))[:10]:
            ref = h["first_refutation"]
            out.append(f"- claim `{h['claim']}` for {h['signature']}: arc {ref['arc']} is `{ref['label']}` in "
                       f"{_arcs(ref['graph'])}")
    return out + [""]


def boundary_section(data: dict, name: str) -> list[str]:
    out = [f"## 3-terminal boundary functions: `{name}`", "",
           "| internal vertices | sides | pairwise | non-pairwise | residual shapes (count) |", "|---|---|---|---|---|"]
    for r in data["rows"]:
        shapes = "; ".join(f"{k}: {v['count']}" for k, v in r["residual_shapes"].items())
        out.append(f"| {r['internal_vertices']} | {r['sides']} | {r['pairwise']} | {r['non_pairwise']} | {shapes} |")
    for r in data["rows"]:
        s = r["smallest_non_pairwise"]
        if s:
            out.append(f"\nSmallest non-pairwise side with {r['internal_vertices']} internal vertices: "
                       f"{_arcs(s['side'])}; f = {s['f']}; residual {s['residual']}.")
    return out + [""]


def main(in_dir: str, out_file: str) -> None:
    sections = ["# Mining summary (generated by experiments/summarize_mining.py)", "",
                "All statements below are about the enumerated finite instances only.", ""]
    for path in sorted(Path(in_dir).glob("*.json")):
        data = json.loads(path.read_text())
        kind = data.get("analysis")
        if kind == "vertex":
            sections += vertex_section(data, path.name)
        elif kind == "arc":
            sections += arc_section(data, path.name)
        elif kind == "boundary":
            sections += boundary_section(data, path.name)
    Path(out_file).write_text("\n".join(sections))
    print(f"wrote {out_file}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
